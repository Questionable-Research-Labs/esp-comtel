#!/usr/bin/env python3
"""Embed the launcher's control page in the firmware.

Gzips src/host/web/index.html into src/host/web_page.h as a PROGMEM byte
array (WEB_PAGE_GZ) plus its length (WEB_PAGE_GZ_LEN), served by web.cpp
with Content-Encoding: gzip. Run it by hand after editing the page and
commit both files -- there is no build step.

Stdlib only. Usage:
    python tools/embed_web.py
"""
import gzip
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "src", "host", "web", "index.html")
OUT = os.path.join(REPO, "src", "host", "web_page.h")


def main():
    with open(SRC, "rb") as f:
        html = f.read()
    # mtime=0 keeps the output byte-identical for an unchanged page
    gz = gzip.compress(html, compresslevel=9, mtime=0)

    lines = [
        "// GENERATED by tools/embed_web.py from src/host/web/index.html -- do not",
        "// edit by hand; edit the page and re-run the script.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "static const size_t WEB_PAGE_GZ_LEN = %d;  // %d bytes before gzip"
        % (len(gz), len(html)),
        "static const uint8_t WEB_PAGE_GZ[] PROGMEM = {",
    ]
    for i in range(0, len(gz), 16):
        chunk = gz[i:i + 16]
        lines.append("  " + ", ".join("0x%02x" % b for b in chunk) + ",")
    lines.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%s: %d bytes (%d gzipped)"
          % (os.path.relpath(OUT, REPO), len(html), len(gz)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
